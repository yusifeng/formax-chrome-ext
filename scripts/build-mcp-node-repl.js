#!/usr/bin/env node

import path from "node:path";
import { build } from "esbuild";

const root = process.cwd();

const bundles = [
  {
    entry: path.join(root, "mcp-node-repl", "server.js"),
    outfile: path.join(root, "mcp-node-repl", "server.js"),
  },
  {
    entry: path.join(root, "mcp-node-repl", "kernel-child.js"),
    outfile: path.join(root, "mcp-node-repl", "kernel-child.js"),
  },
];

for (const bundleConfig of bundles) {
  await build({
    entryPoints: [bundleConfig.entry],
    outfile: bundleConfig.outfile,
    allowOverwrite: true,
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node20",
    sourcemap: false,
    logLevel: "info",
    banner: {
      js: "// Generated by scripts/build-mcp-node-repl.js. Do not edit by hand.",
    },
  });
}
