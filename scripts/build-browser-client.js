#!/usr/bin/env node

import fs from "node:fs/promises";
import path from "node:path";
import { build } from "esbuild";

const root = process.cwd();
const entry = path.join(root, "build", "runtime", "mcp-node-repl", "browser-client.js");
const outfile = path.join(root, "build", "runtime", "scripts", "browser-client.mjs");

await fs.mkdir(path.dirname(outfile), { recursive: true });

await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  sourcemap: false,
  logLevel: "info",
  banner: {
    js: "// Generated by scripts/build-browser-client.js. Do not edit by hand.",
  },
});
