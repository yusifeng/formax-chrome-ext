#!/usr/bin/env node

import fs from "node:fs/promises";
import path from "node:path";
import { browserActionRegistry } from "../shared/action-registry.js";
import { browserActionParameterSchemas } from "../shared/browser-tool-schemas.js";

const root = process.cwd();
const outputPath = path.join(root, "docs/protocol-action-reference.md");
const checkOnly = process.argv.includes("--check");

const [typesSource, protocolSource] = await Promise.all([
  fs.readFile(path.join(root, "shared/types.ts"), "utf8"),
  fs.readFile(path.join(root, "shared/protocol.md"), "utf8")
]);

const registryActions = browserActionRegistry.map((entry) => entry.action);
const typeActions = extractStringUnion(typesSource, "BrowserAction");
const schemaActions = Object.keys(browserActionParameterSchemas);
const protocolActions = extractProtocolActionSections(protocolSource);

const errors = [
  ...compareSets("shared/types.ts BrowserAction", typeActions, "shared/action-registry.ts", registryActions),
  ...compareSets("shared/browser-tool-schemas.ts", schemaActions, "shared/action-registry.ts", registryActions),
  ...registryActions
    .filter((action) => !protocolActions.has(action))
    .map((action) => `shared/protocol.md is missing action section: ### ${action}`)
];

const content = renderReference({
  generatedAt: new Date(0).toISOString(),
  registryActions,
  protocolActions
});

if (errors.length) {
  console.error(errors.map((error) => `- ${error}`).join("\n"));
  process.exit(1);
}

if (checkOnly) {
  let existing = "";
  try {
    existing = await fs.readFile(outputPath, "utf8");
  } catch {
    console.error(`Missing generated protocol action reference: ${path.relative(root, outputPath)}`);
    process.exit(1);
  }

  if (existing !== content) {
    console.error(
      `${path.relative(root, outputPath)} is stale. Run npm run docs:protocol.`
    );
    process.exit(1);
  }

  console.log("Protocol action reference is synchronized.");
} else {
  await fs.writeFile(outputPath, content);
  console.log(`Generated ${path.relative(root, outputPath)}`);
}

function extractStringUnion(source, typeName) {
  const match = source.match(new RegExp(`export type ${typeName} =([\\s\\S]*?);`));
  if (!match) {
    throw new Error(`Unable to find exported union type: ${typeName}`);
  }

  return Array.from(match[1].matchAll(/"([^"]+)"/g), (item) => item[1]);
}

function extractProtocolActionSections(source) {
  const headings = new Set();
  for (const match of source.matchAll(/^### ([A-Za-z][A-Za-z0-9]*)$/gm)) {
    headings.add(match[1]);
  }
  return headings;
}

function compareSets(leftName, leftItems, rightName, rightItems) {
  const left = new Set(leftItems);
  const right = new Set(rightItems);
  const errors = [];

  for (const item of right) {
    if (!left.has(item)) {
      errors.push(`${leftName} is missing ${item} from ${rightName}`);
    }
  }

  for (const item of left) {
    if (!right.has(item)) {
      errors.push(`${leftName} contains ${item}, but ${rightName} does not`);
    }
  }

  return errors;
}

function renderReference({ generatedAt, registryActions, protocolActions }) {
  const lines = [
    "# Protocol Action Reference",
    "",
    "<!-- Generated by scripts/generate-protocol-action-reference.js. Do not edit by hand. -->",
    "",
    `Generated from shared registry and schema sources at ${generatedAt}.`,
    "",
    "This file is intentionally deterministic; the timestamp is fixed so `npm run check:protocol-sync` can detect stale generated content.",
    "",
    "| Action | Tool | Capability | Required params | Risk annotations | Protocol section |",
    "| --- | --- | --- | --- | --- | --- |"
  ];

  for (const entry of browserActionRegistry) {
    const schema = browserActionParameterSchemas[entry.action];
    const required = Array.isArray(schema?.required) && schema.required.length
      ? schema.required.join(", ")
      : "-";
    const annotations = Object.entries(entry.annotations)
      .filter(([, enabled]) => enabled)
      .map(([name]) => name)
      .join(", ") || "-";
    lines.push(
      `| \`${entry.action}\` | \`${entry.toolName}\` | ${entry.capabilityId ? `\`${entry.capabilityId}\`` : "-"} | ${escapeCell(required)} | ${escapeCell(annotations)} | ${protocolActions.has(entry.action) ? "yes" : "missing"} |`
    );
  }

  lines.push("");
  lines.push(`Total actions: ${registryActions.length}`);
  lines.push("");
  return `${lines.join("\n")}\n`;
}

function escapeCell(value) {
  return String(value).replaceAll("|", "\\|");
}
